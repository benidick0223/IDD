const user = (name: string) => `u-${name}`;

function build() {
  const questions: Question[] = [];
  const answers: Record<string, any> = {};
  let n = 0;
  raw.forEach((q, i) => {
    const id = `qs${i + 1}`;
    const answerIds: string[] = [];
    q.a.forEach(([by, text, upvotes, ago, replies], j) => {
      const aid = `as${++n}`;
      answerIds.push(aid);
      answers[aid] = {
        id: aid,
        questionId: id,
        authorId: user(by),
        text,
        timeAgo: ago,
        upvotes,
        replies: (replies || []).map(([rb, rt], k) => ({
          id: `${aid}r${k}`,
          text: rt,
          authorId: user(rb),
        })),
      };
    });
    questions.push({
      id,
      type: q.t,
      title: q.title,
      body: q.body,
      tags: q.tags,
      askerId: user(q.by),
      timeAgo: q.ago,
      upvotes: q.ups,
      routeId: q.route,
      answerIds,
      acceptedAnswerId: q.best !== undefined ? answerIds[q.best] : undefined,
    });
  });
  return { questions, answers };
}

// "3h ago", "Yesterday", "2 weeks ago" -> minutes, for ordering newest first.
function minutesAgo(s: string) {
  const m = s.match(/^(\d+)\s*(min|h|days?|weeks?)/i);
  if (!m) return s === "Yesterday" ? 1440 : 0;
  const n = +m[1];
  const unit = m[2].toLowerCase();
  return unit === "min" ? n : unit === "h" ? n * 60 : unit.startsWith("day") ? n * 1440 : n * 10080;
}

